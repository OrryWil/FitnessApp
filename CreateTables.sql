CREATE TABLE WorkoutInfo (
	WorkoutInfoId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	CoachId INT NOT NULL,
	WorkoutName VARCHAR(254) NOT NULL,
	WorkoutDate DATE NOT NULL,

	FOREIGN KEY (CoachId) REFERENCES Coaches(CoachId)
);
CREATE TABLE WorkoutAssignments(
	AssignmentId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	WorkoutInfoId INT NOT NULL,
	AthleteId INT NOT NULL,

	FOREIGN KEY (WorkoutInfoId) REFERENCES WorkoutInfo(WorkoutInfoId),
	FOREIGN KEY (AthleteId) REFERENCES Athletes(AthleteId),
	UNIQUE(WorkoutInfoId, AthleteId)
);
CREATE TABLE Workouts(
	WorkoutId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	WorkoutInfoId INT NOT NULL,
	WorkoutGroup INT NOT NULL,
	ExerciseId INT NOT NULL,
	WorkoutSets INT NOT NULL CHECK (WorkoutSets > 0),
	WorkoutReps INT NOT NULL CHECK (WorkoutReps > 0),

	FOREIGN KEY (WorkoutInfoId) REFERENCES WorkoutInfo(WorkoutInfoId),
	FOREIGN KEY (ExerciseId) REFERENCES Exercises(ExerciseId)
);
CREATE TABLE WorkoutResults(
	ResultId INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	WorkoutId INT NOT NULL,
	AssignmentId INT NOT NULL,
	AskedWeight DECIMAL(8,2) CHECK (AskedWeight >= 0),
	ActualWeightDone DECIMAL(8,2) CHECK (ActualWeightDone >=0),
	Completed BOOLEAN NOT NULL DEFAULT FALSE,

	FOREIGN KEY (WorkoutId) REFERENCES Workouts(WorkoutId),
	FOREIGN KEY (AssignmentId) REFERENCES WorkoutAssignments(AssignmentId),
	UNIQUE (WorkoutId, AssignmentId)

	
);
